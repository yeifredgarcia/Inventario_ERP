-- Tabla: inventario_general
-- El estado de vencimiento (Disponible / Por Vencer / Vencido) ya no se guarda:
-- se calcula en la vista v_inventario a partir de fecha_vencimiento.
CREATE TABLE `inventario_general` (
  `id_producto` bigint(20) UNSIGNED NOT NULL AUTO_INCREMENT,
  `nombre_producto` varchar(150) NOT NULL,
  `id_categoria` int(11) NOT NULL,
  `id_presentacion` bigint(20) UNSIGNED NOT NULL,
  `cantidad` int(11) NOT NULL DEFAULT 0,
  `fecha_vencimiento` date DEFAULT NULL,
  `status` enum('Activo','Inactivo') NOT NULL DEFAULT 'Activo',
  `fecha_registro` datetime NOT NULL DEFAULT current_timestamp(),
  `fecha_modificacion` datetime DEFAULT NULL ON UPDATE current_timestamp(),
  `usuario_registro` int(10) UNSIGNED DEFAULT NULL,
  `usuario_modificacion` int(10) UNSIGNED DEFAULT NULL,
  PRIMARY KEY (`id_producto`),
  UNIQUE KEY `uq_producto_lote` (`nombre_producto`,`id_categoria`,`id_presentacion`,`fecha_vencimiento`),
  KEY `idx_inv_categoria` (`id_categoria`),
  KEY `idx_inv_presentacion` (`id_presentacion`),
  CONSTRAINT `chk_inv_cantidad` CHECK (`cantidad` >= 0)
