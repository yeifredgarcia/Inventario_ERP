-- Vista de consulta: calcula el estado de vencimiento (90 días o menos = "Por Vencer")
CREATE VIEW `v_inventario` AS
SELECT i.id_producto, i.nombre_producto, i.id_categoria, c.nombre_categoria,
       i.id_presentacion, p.nombre_presentacion, i.cantidad, i.fecha_vencimiento,
       CASE
         WHEN i.fecha_vencimiento IS NULL THEN 'Disponible'
         WHEN i.fecha_vencimiento < CURDATE() THEN 'Vencido'
         WHEN i.fecha_vencimiento <= DATE_ADD(CURDATE(), INTERVAL 90 DAY) THEN 'Por Vencer'
         ELSE 'Disponible'
       END AS estado_vencimiento,
       i.status, i.fecha_registro, i.fecha_modificacion
FROM inventario_general i
INNER JOIN categorias c ON c.id_categoria = i.id_categoria
INNER JOIN presentaciones p ON p.id_presentacion = i.id_presentacion;
